// Builds frontend/src/app/features/public/shared/morocco-outline.ts: the outline of the Kingdom of Morocco, southern provinces included,
// from Natural Earth (public domain, https://www.naturalearthdata.com) as packaged by `world-atlas` (10 m scale).
//
//   cd tools/morocco-map && npm install && npm run build
//
// Natural Earth lists Morocco (504) and Western Sahara (732) as two features; the Moroccan national map is their union, so the shared
// border is dissolved. Only the mainland is kept. The ring is then thinned (Douglas-Peucker in Mercator space) to a few hundred points:
// the coast stays recognisable, the file stays small.
import { readFileSync, writeFileSync } from 'node:fs';
import { merge } from 'topojson-client';

const TOLERANCE = Number(process.env.TOLERANCE ?? 0.012); // degrees (about 1.3 km): the largest deviation allowed from the real coast
const OUT = new URL('../../frontend/src/app/features/public/shared/morocco-outline.ts', import.meta.url);

const topology = JSON.parse(readFileSync(new URL('./node_modules/world-atlas/countries-10m.json', import.meta.url), 'utf8'));
const parts = topology.objects.countries.geometries.filter((g) => ['504', '732'].includes(String(g.id)));
if (parts.length !== 2) throw new Error('Morocco and Western Sahara not found in the data');
const union = merge(topology, parts); // MultiPolygon, [lon, lat]

const mercatorY = (lat) => (180 / Math.PI) * Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360));
const planarArea = (ring) => Math.abs(ring.reduce((a, [x1, y1], i) => { const [x2, y2] = ring[(i + 1) % ring.length]; return a + (x1 * y2 - x2 * y1); }, 0)) / 2;
const sphericalAreaKm2 = (ring) => {
  const R = 6371.0088, rad = Math.PI / 180;
  let sum = 0;
  for (let i = 0; i < ring.length; i++) { const [l1, p1] = ring[i], [l2, p2] = ring[(i + 1) % ring.length]; sum += (l2 - l1) * rad * (2 + Math.sin(p1 * rad) + Math.sin(p2 * rad)); }
  return Math.abs((sum * R * R) / 2);
};

const mainland = union.coordinates.map((poly) => poly[0]).sort((a, b) => planarArea(b) - planarArea(a))[0];
const open = mainland.slice(0, -1); // the ring is closed in the data: drop the repeated first point

function simplify(points, tolerance) {
  const p = points.map(([lon, lat]) => [lon, mercatorY(lat)]);
  const keep = new Array(p.length).fill(false);
  keep[0] = keep[p.length - 1] = true;
  const stack = [[0, p.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let max = 0, idx = -1;
    const [ax, ay] = p[a], [bx, by] = p[b], dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * p[i][0] - dx * p[i][1] + bx * ay - by * ax) / len;
      if (d > max) { max = d; idx = i; }
    }
    if (max > tolerance && idx > 0) { keep[idx] = true; stack.push([a, idx], [idx, b]); }
  }
  return points.filter((_, i) => keep[i]);
}

// The ring is a loop: split it at its two farthest-apart vertices so no corner is favoured as the "start".
const half = Math.floor(open.length / 2);
const first = simplify(open.slice(0, half + 1), TOLERANCE), second = simplify([...open.slice(half), open[0]], TOLERANCE);
const ring = [...first, ...second.slice(1, -1)]
  .map(([lon, lat]) => [Math.round(lon * 1000) / 1000, Math.round(lat * 1000) / 1000])
  .filter((p, i, a) => i === 0 || p[0] !== a[i - 1][0] || p[1] !== a[i - 1][1]);

const lons = ring.map((p) => p[0]), lats = ring.map((p) => p[1]);
const area = Math.round(sphericalAreaKm2(ring));
console.log(`raw ${open.length} points -> ${ring.length} points (tolerance ${TOLERANCE}°)`);
console.log(`longitude ${Math.min(...lons)} .. ${Math.max(...lons)}, latitude ${Math.min(...lats)} .. ${Math.max(...lats)}`);
console.log(`area ${area.toLocaleString('en')} km² (mainland, after thinning)`);

const rows = [];
for (let i = 0; i < ring.length; i += 6) rows.push('  ' + ring.slice(i, i + 6).map(([lon, lat]) => `[${lon}, ${lat}]`).join(', ') + ',');
writeFileSync(OUT, `// GENERATED by tools/morocco-map/build.mjs. Do not edit by hand: change the tool and run it again.
// Source: Natural Earth (public domain), 10 m countries via the npm package world-atlas. Morocco and Western Sahara are joined, as on the
// Moroccan national map: the whole territory of the Kingdom, southern provinces included. Mainland only, thinned to ${TOLERANCE}° (~1.3 km).
// This is open data, not ANAGEM's official cartography: replace it if the association supplies its own (docs/requirements, question 1).

/** The outline as [longitude, latitude] pairs (WGS 84), clockwise or counter-clockwise as in the source, not repeated at the end. */
export const MOROCCO_OUTLINE: readonly (readonly [number, number])[] = [
${rows.join('\n')}
];
`);
console.log('written', OUT.pathname.split('/').slice(-4).join('/'));
