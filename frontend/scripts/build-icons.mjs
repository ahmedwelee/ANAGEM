// Builds public/icons.svg (one <symbol> per icon) from the Lucide set in node_modules/lucide-static.
// Add a name to ICONS, run `npm run icons`, then use <app-icon name="..."/>.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const ICONS = `
layout-dashboard newspaper book-open calendar-days folder-open tags image images handshake layout-template settings users shield-check history mail
log-out user languages menu x plus search pencil trash-2 eye eye-off check circle-check triangle-alert info chevron-down chevron-left chevron-right chevron-up
upload download file-text link link-2-off bold italic underline heading-2 heading-3 list list-ordered quote table image-plus undo-2 redo-2 star send archive
clock calendar-clock globe external-link copy refresh-cw lock key-round loader-circle ellipsis funnel trending-up megaphone map-pin circle-alert paperclip
file-image panel-left-close eraser save rocket circle-x inbox mail-open rotate-ccw move-right
phone calendar share-2 arrow-right arrow-left tag building-2 compass leaf scale landmark lightbulb user-plus shield-check printer map
`.split(/\s+/).filter(Boolean);

const dir = 'node_modules/lucide-static/icons';
const missing = [];
const symbols = [];
for (const name of ICONS) {
  const file = `${dir}/${name}.svg`;
  if (!existsSync(file)) { missing.push(name); continue; }
  const svg = readFileSync(file, 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<!--[\s\S]*?-->/g, '').trim();
  symbols.push(`<symbol id="${name}" viewBox="0 0 24 24">${inner}</symbol>`);
}
// Brand icons were removed from Lucide 1.x: small hand-kept symbols (24x24, stroke style) for the social links.
const BRANDS = {
  linkedin: '<path d="M16 8a6 6 0 0 1 6 6v7h-4v-7a2 2 0 0 0-2-2 2 2 0 0 0-2 2v7h-4v-7a6 6 0 0 1 6-6z"/><rect width="4" height="12" x="2" y="9"/><circle cx="4" cy="4" r="2"/>',
  facebook: '<path d="M18 2h-3a5 5 0 0 0-5 5v3H7v4h3v8h4v-8h3l1-4h-4V7a1 1 0 0 1 1-1h3z"/>',
  'x-social': '<path d="M4 4l11.733 16h4.267l-11.733 -16z"/><path d="M4 20l6.768 -6.768m2.46 -2.46l6.772 -6.772"/>',
  youtube: '<path d="M2.5 17a24.12 24.12 0 0 1 0-10 2 2 0 0 1 1.4-1.4 49.56 49.56 0 0 1 16.2 0A2 2 0 0 1 21.5 7a24.12 24.12 0 0 1 0 10 2 2 0 0 1-1.4 1.4 49.55 49.55 0 0 1-16.2 0A2 2 0 0 1 2.5 17"/><path d="m10 15 5-3-5-3z"/>',
};
for (const [id, inner] of Object.entries(BRANDS)) symbols.push(`<symbol id="${id}" viewBox="0 0 24 24">${inner}</symbol>`);
writeFileSync('public/icons.svg', `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Lucide (ISC licence). Generated by scripts/build-icons.mjs -->\n${symbols.join('\n')}\n</svg>\n`);
console.log(`icons.svg: ${symbols.length} icons`);
if (missing.length) { console.error('Missing icons:', missing.join(', ')); process.exitCode = 1; }
